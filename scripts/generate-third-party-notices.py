def run(cmd: list[str], cwd: Path) -> str:
    return subprocess.run(cmd, cwd=cwd, check=True, capture_output=True, text=True).stdout


def rust_crates() -> list[tuple[str, str, str, str]]:
    out = run(
        ["cargo", "tree", "--offline", "--locked", "-e", "normal,build", "--target", "all",
         "--prefix", "none", "--format", "{p}|{l}|{r}"],
        TAURI,
    )
    rows = set()
    for line in out.splitlines():
        line = line.replace(" (*)", "").replace(" (proc-macro)", "").strip()
        if not line or "|" not in line:
            continue
        package, license_id, repo = (line.split("|") + ["", ""])[:3]
        name, _, version = package.partition(" v")
        if name == "app":
            continue
        version = version.split(" ")[0]
        rows.add((name, version, license_id or "UNKNOWN", repo))
    return sorted(rows)


def npm_packages() -> list[tuple[str, str, str, str, str]]:
    tree = json.loads(run(["npm", "ls", "--omit=dev", "--all", "--json"], ROOT) or "{}")
    seen: dict[tuple[str, str], tuple[str, str, str]] = {}

    def walk(node: dict) -> None:
        for name, dep in (node.get("dependencies") or {}).items():
            version = dep.get("version")
            if not version or (name, version) in seen or name in LOCAL_NPM_PACKAGES:
                continue
            path = dep.get("path") or str(ROOT / "node_modules" / name)
            license_id, repo = "UNKNOWN", ""
            try:
                manifest = json.loads(Path(path, "package.json").read_text(encoding="utf-8"))
                value = manifest.get("license") or manifest.get("licenses")
                if isinstance(value, str):
                    license_id = value
                elif isinstance(value, dict):
                    license_id = value.get("type", "UNKNOWN")
                elif isinstance(value, list):
                    license_id = " OR ".join(v.get("type", "?") for v in value)
                repo_value = manifest.get("repository")
                repo = repo_value if isinstance(repo_value, str) else (repo_value or {}).get("url", "")
            except (OSError, ValueError):
                pass
            if license_id == "UNKNOWN":
                license_id = _license_from_file(Path(path)) or "UNKNOWN"
            seen[(name, version)] = (license_id, repo, path)
            walk(dep)

    walk(tree)
    return sorted((n, v, lic, repo, path) for (n, v), (lic, repo, path) in seen.items())


def _license_from_file(directory: Path) -> str | None:
    for candidate in sorted(directory.glob("LICEN[CS]E*")):
        head = candidate.read_text(errors="replace")[:200]
        if "MIT License" in head or head.lstrip().startswith("MIT"):
            return "MIT (from LICENSE file)"
    return None


def _clean_repo(url: str) -> str:
    url = url.removeprefix("git+").removesuffix(".git")
    if url.startswith("github:"):
        url = "https://github.com/" + url.removeprefix("github:")
    return url.replace("git://", "https://").replace("ssh://git@", "https://")


def render() -> str:
    crates = rust_crates()
    packages = npm_packages()
    lines = [HEADER, REQUIRED_NOTICES, DATA_NOTICES]
    lines.append(f"## Rust crates ({len(crates)})\n")
    lines.append("All target platforms; normal and build dependencies only.\n")
    lines.append("| Crate | Version | License | Repository |")
    lines.append("|---|---|---|---|")
    lines += [f"| {n} | {v} | {lic} | {repo} |" for n, v, lic, repo in crates]
    lines.append("")
    lines.append(f"## npm packages bundled into the frontends ({len(packages)})\n")
    lines.append("| Package | Version | License | Repository |")
    lines.append("|---|---|---|---|")
    lines += [f"| {n} | {v} | {lic} | {_clean_repo(repo)} |" for n, v, lic, repo, _ in packages]
    lines.append("")
    return "\n".join(lines)


def collect_license_texts(destination: Path) -> None:
    meta = json.loads(run(["cargo", "metadata", "--offline", "--locked", "--format-version", "1"], TAURI))
    shipped = {(n, v) for n, v, _, _ in rust_crates()}
    texts: dict[str, list] = {}
    missing: list[str] = []

    def add_dir(label: str, directory: str) -> None:
        files = [
            f for f in sorted(glob.glob(os.path.join(directory, "*")))
            if os.path.basename(f).upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE"))
        ]
        if not files:
            missing.append(label)
        for path in files:
            text = Path(path).read_text(errors="replace")
            texts.setdefault(hashlib.sha256(text.encode()).hexdigest(), [text, []])[1].append(label)

    for package in meta["packages"]:
        if (package["name"], package["version"]) in shipped and package["source"]:
            add_dir(f'{package["name"]} {package["version"]} (Rust)', os.path.dirname(package["manifest_path"]))
    for name, version, _, _, path in npm_packages():
        add_dir(f"{name} {version} (npm)", path)

    out = ["THIRD-PARTY LICENSE TEXTS (generated)", ""]
    for text, users in texts.values():
        out += ["=" * 78, "Used by: " + ", ".join(sorted(set(users))), "=" * 78, text.rstrip(), ""]
    if missing:
        out += ["=" * 78, "No license file shipped in the package; see the SPDX id in",
                "THIRD_PARTY_NOTICES.md and the canonical text at https://spdx.org/licenses/ :",
                *sorted(missing), ""]
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {destination} ({len(texts)} unique texts, {len(missing)} packages without a license file)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if THIRD_PARTY_NOTICES.md is out of date")
    parser.add_argument("--licenses-out", type=Path, help="also write full license texts to this file")
    args = parser.parse_args()
    content = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print("THIRD_PARTY_NOTICES.md is out of date; run scripts/generate-third-party-notices.py")
            return 1
        print("THIRD_PARTY_NOTICES.md is up to date")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
        print(f"wrote {OUTPUT}")
    if args.licenses_out:
        collect_license_texts(args.licenses_out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
